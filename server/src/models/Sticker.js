import mongoose from "mongoose";

// A single link on a page, e.g. { label: "Instagram", url: "https://..." }.
const linkSchema = new mongoose.Schema(
  {
    label: { type: String, default: "", trim: true },
    url: { type: String, default: "", trim: true },
  },
  { _id: false }
);

// A content block in the block-based page builder. `props` is intentionally
// flexible (Mixed) because each block type has its own shape; the API validates
// the exact shape per type with zod before saving.
const blockSchema = new mongoose.Schema(
  {
    id: { type: String, required: true }, // stable key, generated by the client
    type: { type: String, required: true },
    props: { type: mongoose.Schema.Types.Mixed, default: {} },
  },
  { _id: false }
);

// The editable page content attached to a sticker.
//
// `blocks` is the source of truth for the block-based editor. The legacy
// title/description/imageUrl/note/links fields are kept for backward
// compatibility (older stickers + seed data): the public page falls back to
// them when a sticker has no blocks yet.
const pageSchema = new mongoose.Schema(
  {
    title: { type: String, default: "", trim: true },
    description: { type: String, default: "", trim: true },
    imageUrl: { type: String, default: "", trim: true },
    note: { type: String, default: "", trim: true }, // owner's note to the finder
    links: { type: [linkSchema], default: [] },
    blocks: { type: [blockSchema], default: [] },
  },
  { _id: false }
);

const stickerSchema = new mongoose.Schema(
  {
    // Public, permanent code that appears in the printed URL /q/:code.
    code: { type: String, required: true, unique: true, index: true },

    // Only the bcrypt hash of the claim code is stored — never the plaintext.
    claimCodeHash: { type: String, required: true },

    // Groups stickers created together (used by admin CSV/PDF downloads).
    batchId: { type: String, default: null, index: true },

    owner: { type: mongoose.Schema.Types.ObjectId, ref: "User", default: null },

    status: {
      type: String,
      enum: ["unclaimed", "active", "paused", "lost"],
      default: "unclaimed",
    },

    template: {
      type: String,
      enum: ["lost_found", "links"],
      default: "lost_found",
    },

    page: { type: pageSchema, default: () => ({}) },

    // Denormalized counter so the dashboard doesn't have to count Scan rows.
    scanCount: { type: Number, default: 0 },
  },
  { timestamps: true }
);

// Safety net: the claim hash must never be serialized to any client.
stickerSchema.set("toJSON", {
  transform: (_doc, ret) => {
    delete ret.claimCodeHash;
    delete ret.__v;
    return ret;
  },
});

export default mongoose.model("Sticker", stickerSchema);
